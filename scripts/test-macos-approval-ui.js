const assert = require("node:assert/strict");
const { clipElement, optionalBoolean, doublePair, asciiKey } = require("./macos-approval-ui.js");
assert.deepEqual(asciiKey("a"), [0, 0]);
assert.deepEqual(asciiKey("_"), [27, 131072]);
assert.throws(() => asciiKey("中"));
const geometry = Buffer.alloc(16);
geometry.writeDoubleLE(-12.5, 0);
geometry.writeDoubleLE(768, 8);
assert.deepEqual(doublePair(geometry.toString("base64")), [-12.5, 768]);
assert.throws(() => doublePair("AAAA"));
assert.equal(optionalBoolean(() => { throw new Error("Native symbol unavailable"); }), null);
assert.equal(optionalBoolean(() => false), false);
assert.equal(optionalBoolean(() => true), true);
const group = clipElement([0, 0], [400, 1800], [0, 0, 400, 500], false);
assert.equal(group.visible, true);
assert.deepEqual(group.clip, [0, 0, 400, 500]);
assert.equal(clipElement([20, 420], [150, 30], group.clip, true).visible, true);
assert.equal(clipElement([20, 700], [150, 30], group.clip, true).visible, false);
assert.equal(clipElement([0, 600], [400, 200], group.clip, false).visible, false);
console.log("approval geometry passed");
